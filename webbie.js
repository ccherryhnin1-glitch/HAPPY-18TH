/* ============================================================
   3. EVENT LISTENERS & DOM INITIALIZATION
   ============================================================ */
document.addEventListener('DOMContentLoaded', () => {

    /* --- Render Envelope Grid --- */
    const grid = document.getElementById('gridContainer');
    if (grid && typeof letterboxData !== 'undefined') {
        grid.innerHTML = letterboxData.map((letter, index) => `
            <div class="envelope" onclick="openLetter(${index})">
                <div class="envelope-badge">
                    <i class="${letter.icon}"></i>
                </div>
                <div class="envelope-title">${letter.title}</div>
                <div class="envelope-subtitle">${letter.subtitle}</div>
            </div>
        `).join('');
    }

    /* --- Countdown Logic --- */
    const daysEl = document.getElementById('days');
    if (daysEl) {
        const targetDate = new Date('October 2, 2026 00:00:00').getTime();

        function updateCountdown() {
            const now = new Date().getTime();
            const difference = targetDate - now;

            if (difference > 0) {
                const days = Math.floor(difference / (1000 * 60 * 60 * 24));
                const hours = Math.floor((difference % (1000 * 60 * 60 * 24)) / (1000 * 60 * 60));
                const minutes = Math.floor((difference % (1000 * 60 * 60)) / (1000 * 60));
                const seconds = Math.floor((difference % (1000 * 60)) / 1000);

                document.getElementById('days').innerText = String(days).padStart(2, '0');
                document.getElementById('hours').innerText = String(hours).padStart(2, '0');
                document.getElementById('minutes').innerText = String(minutes).padStart(2, '0');
                document.getElementById('seconds').innerText = String(seconds).padStart(2, '0');
            } else {
                const countdownBox = document.querySelector('.countdown-box');
                if (countdownBox) {
                    countdownBox.innerHTML = "<h3> Happy 18th Birthday! </h3>";
                }
            }
        }

        updateCountdown();
        setInterval(updateCountdown, 1000);
    }

    /* --- Modal Outer Click Closers --- */
    const letterModal = document.getElementById('letterModal');
    if (letterModal) {
        letterModal.addEventListener('click', (e) => {
            if (e.target === letterModal) closeModal();
        });
    }

    const playlistModal = document.getElementById('playlistModal');
    if (playlistModal) {
        playlistModal.addEventListener('click', (e) => {
            if (e.target === playlistModal) closePlaylistModal();
        });
    }

    /* --- Make a Wish & Confetti --- */
    const wishBtn = document.getElementById('wishBtn');
    if (wishBtn) {
        wishBtn.addEventListener('click', () => {
            const flames = document.querySelectorAll('.flame');
            flames.forEach(flame => flame.style.display = 'none');

            if (typeof confetti === 'function') {
                confetti({
                    particleCount: 120,
                    spread: 80,
                    origin: { y: 0.6 },
                    colors: ['#ff69b4', '#e0115f', '#9b51e0', '#fbcfe8', '#ffffff']
                });
            }

            const wishStatus = document.getElementById('wishStatus');
            if (wishStatus) {
                wishStatus.innerText = "✨ Your wish was sent to the stars! ✨";
            }
        });
    }
});

/* ============================================================
   4. GLOBAL FUNCTIONS
   ============================================================ */
function openLetter(index) {
    const item = letterboxData[index];
    const modalOverlay = document.getElementById('letterModal');
    if (modalOverlay && item) {
        const titleEl = document.getElementById('modalTitle');
        const textEl = document.getElementById('modalText');

        if (titleEl) {
            titleEl.innerText = `${item.title} ${item.subtitle}`;
        }
        if (textEl) {
            textEl.innerText = item.text;
        }

        modalOverlay.classList.add('active');
    }
}

function closeModal() {
    const modalOverlay = document.getElementById('letterModal');
    if (modalOverlay) {
        modalOverlay.classList.remove('active');
    }
}

function openPlaylistModal(index) {
    const item = playlistData[0];
    const modal = document.getElementById('playlistModal');
    if (modal && item) {
        document.getElementById('playlistTitle').innerText = item.title;
        document.getElementById('playlistDescription').innerText = item.description;
        document.getElementById('playlistScanImage').src = item.scanCode;
        document.getElementById('spotifyDirectLink').href = item.spotifyUrl;
        modal.classList.add('active');
    }
}

function closePlaylistModal() {
    const modal = document.getElementById('playlistModal');
    if (modal) {
        modal.classList.remove('active');
    }
}